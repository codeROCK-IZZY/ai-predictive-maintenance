import clsx from "clsx";
import type { Factor, Prediction, Recommendation } from "../api/types";
import { dateTime, healthStroke, humanize, pct, RISK_STYLE } from "../lib/format";
import { RiskBadge } from "./ui";

export function HealthGauge({ score }: { score: number }) {
  return (
    <div className="flex flex-col items-center">
      <div className="relative flex h-28 w-28 items-center justify-center rounded-full bg-slate-100"
        role="img" aria-label={`Health score ${score} out of 100`}>
        <svg className="absolute inset-0 -rotate-90" viewBox="0 0 36 36">
          <circle cx="18" cy="18" r="15.9" fill="none" stroke="#e2e8f0" strokeWidth="3" />
          <circle cx="18" cy="18" r="15.9" fill="none" strokeWidth="3" strokeLinecap="round"
            className={healthStroke(score)} strokeDasharray={`${score} 100`} />
        </svg>
        <span className="text-2xl font-semibold tabular-nums">{score}</span>
      </div>
      <span className="mt-1 text-xs text-slate-500">Health score</span>
    </div>
  );
}

export function FactorList({ factors }: { factors: Factor[] }) {
  const max = Math.max(...factors.map((f) => Math.abs(f.contribution)), 1e-9);
  return (
    <ul className="space-y-2">
      {factors.map((f) => (
        <li key={f.signal}>
          <div className="flex items-start justify-between gap-3 text-sm">
            <span className="text-slate-800">{f.text}</span>
            <span className={clsx("shrink-0 text-xs font-medium", f.contribution > 0 ? "text-red-700" : "text-emerald-700")}>
              {f.contribution > 0 ? "▲ raises risk" : "▼ lowers risk"}
            </span>
          </div>
          <div className="mt-1 h-1.5 w-full rounded bg-slate-100">
            <div className={clsx("h-full rounded", f.contribution > 0 ? "bg-red-400" : "bg-emerald-400")}
              style={{ width: `${(Math.abs(f.contribution) / max) * 100}%` }} />
          </div>
        </li>
      ))}
    </ul>
  );
}

export function RecommendationList({ recs }: { recs: Recommendation[] }) {
  return (
    <ul className="space-y-2">
      {recs.map((r, i) => (
        <li key={i} className="rounded-lg border border-slate-200 p-3 text-sm">
          <div className="mb-1 flex items-center gap-2">
            <span className={clsx("rounded px-1.5 py-0.5 text-xs font-medium capitalize ring-1 ring-inset",
              r.priority === "low" ? "bg-slate-50 text-slate-700 ring-slate-300" : RISK_STYLE[r.priority].badge)}>
              {r.priority}
            </span>
            <span className="text-xs text-slate-500" title="Generated by deterministic engineering rules, not by AI">
              Rule-based recommendation
            </span>
          </div>
          {r.action}
        </li>
      ))}
    </ul>
  );
}

export function PredictionSummary({ p }: { p: Prediction }) {
  const dq = p.explanation.data_quality;
  return (
    <div className="flex flex-wrap items-center gap-8">
      <HealthGauge score={p.health_score} />
      <dl className="grid flex-1 grid-cols-2 gap-x-6 gap-y-3 text-sm sm:grid-cols-3">
        <div><dt className="text-xs text-slate-500">Risk level</dt><dd><RiskBadge risk={p.risk_level} /></dd></div>
        <div><dt className="text-xs text-slate-500">Failure probability ({p.model?.horizon_days ?? 7} days)</dt>
          <dd className="text-lg font-semibold tabular-nums">{pct(p.failure_probability, 1)}</dd></div>
        <div><dt className="text-xs text-slate-500">Est. remaining useful life</dt>
          <dd className="font-medium tabular-nums">{p.rul_days == null ? "—" : p.rul_days >= 60 ? "≥ 60 days" : `${p.rul_days} days`}</dd></div>
        <div><dt className="text-xs text-slate-500">Suspected failure mode</dt>
          <dd className="font-medium capitalize">{humanize(p.explanation.suspected_failure_mode)}</dd></div>
        <div><dt className="text-xs text-slate-500">Anomaly score</dt>
          <dd className="tabular-nums" title="Share of healthy history that looks less unusual">{pct(p.anomaly_score, 1)}</dd></div>
        <div><dt className="text-xs text-slate-500">Data as of</dt><dd>{dateTime(p.as_of)}</dd></div>
      </dl>
      {(dq.stale || !dq.baseline_available) && (
        <p className="w-full rounded-md bg-amber-50 px-3 py-2 text-xs text-amber-800" role="status">
          {dq.stale && "No recent sensor data — this prediction is based on the last available readings. "}
          {!dq.baseline_available && "Less than 7 days of history: baseline comparisons are not yet reliable."}
        </p>
      )}
      <p className="w-full text-xs text-slate-500">
        Model v{p.model?.version} ({humanize(p.model?.algorithm)}). {p.explanation.caveat}
      </p>
    </div>
  );
}
