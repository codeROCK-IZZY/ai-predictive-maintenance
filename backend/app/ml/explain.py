"""Turn SHAP contributions into plain-language explanation factors.

SHAP contributions are in log-odds: positive values push the failure risk up,
negative values push it down. The text templates below are deterministic — the
explanation is not generated by an AI model.
"""

from __future__ import annotations

import math
from typing import Any

from app.modules.equipment.catalog import EQUIPMENT_TYPES

_SENSOR_INFO = {s.code: (s.name, s.unit) for t in EQUIPMENT_TYPES for s in t.sensors}
for _code in ("bearing_temp", "winding_temp"):
    _name, _unit = _SENSOR_INFO[_code]
    _SENSOR_INFO[f"{_code}_rise"] = (f"{_name} rise above ambient", _unit)

_WINDOW = {"6h": "6-hour", "24h": "24-hour", "72h": "3-day"}


def describe(feature: str, value: float | None) -> str:
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return f"{feature}: no data"
    if feature == "age_days":
        return f"Equipment age is {value / 365:.1f} years"
    if feature == "days_since_service":
        return f"{value:.0f} days since the last maintenance"
    if feature.startswith("type_"):
        return "Equipment type"
    sensor, _, stat = feature.partition("__")
    name, unit = _SENSOR_INFO.get(sensor, (sensor, ""))
    kind, _, window = stat.partition("_")
    w = _WINDOW.get(window, window)
    if kind == "mean":
        return f"{name} {w} average is {value:.1f} {unit}"
    if kind == "std":
        return f"{name} variability ({w} std. dev.) is {value:.2f} {unit}"
    if kind == "max":
        return f"{name} peaked at {value:.1f} {unit} in the last {w} window"
    if kind == "z":
        direction = "above" if value >= 0 else "below"
        return f"{name} ({w} average) is {abs(value):.1f}σ {direction} this unit's normal level"
    if kind == "slope":
        direction = "rising" if value >= 0 else "falling"
        return f"{name} has been {direction} over the {w} window ({value:+.2f}σ per day)"
    return f"{feature} = {value:.3g}"


def _group_of(feature: str) -> str:
    return feature.split("__")[0]


def top_factors(
    feature_names: list[str] | tuple[str, ...], values: list[float], contributions: list[float], k: int = 5
) -> list[dict[str, Any]]:
    """Top explanation factors, grouped by signal ("grouped SHAP").

    Features derived from the same sensor are strongly correlated (e.g. 24 h and
    72 h averages). Individually, a model can give them large *offsetting*
    contributions, which reads as nonsense ("temperature is high → lower risk").
    SHAP values are additive, so summing them per sensor gives each sensor's total
    effect. The text comes from the group's strongest feature pushing in the same
    direction as the total; individual features are kept under ``details``.
    """
    groups: dict[str, list[int]] = {}
    for i, name in enumerate(feature_names):
        if name.startswith("type_"):
            continue
        groups.setdefault(_group_of(name), []).append(i)
    totals = {g: sum(contributions[i] for i in idx) for g, idx in groups.items()}
    ranked = sorted(totals, key=lambda g: abs(totals[g]), reverse=True)
    out: list[dict[str, Any]] = []
    for g in ranked:
        total = totals[g]
        if len(out) >= k or abs(total) < 1e-6:
            break
        idx = groups[g]
        same_sign = [i for i in idx if contributions[i] * total > 0] or idx
        lead = max(same_sign, key=lambda i: abs(contributions[i]))
        v = values[lead]
        out.append(
            {
                "signal": g,
                "feature": feature_names[lead],
                "value": None if v is None or math.isnan(v) else round(float(v), 4),
                "contribution": round(float(total), 4),
                "effect": "increases risk" if total > 0 else "decreases risk",
                "text": describe(feature_names[lead], v),
                "details": [
                    {"feature": feature_names[i], "contribution": round(float(contributions[i]), 4)}
                    for i in sorted(idx, key=lambda i: abs(contributions[i]), reverse=True)[:4]
                ],
            }
        )
    return out
